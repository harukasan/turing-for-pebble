// Write core/palettes.h, the built-in palette stops of core/rd.c, from
// lib/palettes.ts. With --check, exit 1 if the file differs instead.
//
//   node --experimental-transform-types scripts/gen-palettes.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { PALETTES, PALETTE_MAX_STOPS } from "../lib/palettes.ts";

const path = new URL("../core/palettes.h", import.meta.url);
const zero = "{0, 0, 0}";
const rows = PALETTES.map((palette) => {
  const stops = palette.stops.map((s) => `{${s.join(", ")}}`);
  while (stops.length < PALETTE_MAX_STOPS) stops.push(zero);
  return `    {${stops.join(", ")}}, /* ${palette.id} */`;
});
const text = `/*
 * Built-in palette stops for core/rd.c, generated by scripts/gen-palettes.mjs
 * from lib/palettes.ts, where the colormap sources are recorded. Do not
 * edit. Palette i has PALETTE_STOP_COUNT[i] stops equally spaced from
 * intensity 0 to 1.0, and none for the monochrome threshold palette.
 */
/* clang-format off */
#define PALETTE_BUILTIN_COUNT ${PALETTES.length}

static const uint8_t PALETTE_STOP_COUNT[PALETTE_BUILTIN_COUNT] = {${PALETTES.map((p) => p.stops.length).join(", ")}};

static const uint8_t PALETTE_STOPS[PALETTE_BUILTIN_COUNT][RD_PALETTE_MAX_STOPS][3] = {
${rows.join("\n")}
};
`;
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== text) {
    console.error("core/palettes.h is stale: run scripts/gen-palettes.mjs");
    process.exit(1);
  }
} else {
  writeFileSync(path, text);
}
